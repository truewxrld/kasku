CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(160) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  is_demo BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS wallets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name VARCHAR(80) NOT NULL,
  type VARCHAR(20) NOT NULL CHECK (type IN ('cash','bank','ewallet')),
  opening_balance NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (opening_balance >= 0),
  description VARCHAR(255),
  UNIQUE (id, user_id), UNIQUE (user_id, name)
);
CREATE TABLE IF NOT EXISTS categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name VARCHAR(80) NOT NULL,
  kind VARCHAR(10) NOT NULL CHECK (kind IN ('income','expense')),
  color VARCHAR(20) NOT NULL CHECK (color IN ('green','orange','blue','pink')),
  UNIQUE (id, user_id), UNIQUE (user_id, name)
);
CREATE TABLE IF NOT EXISTS transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  wallet_id BIGINT NOT NULL,
  category_id BIGINT NOT NULL,
  title VARCHAR(100) NOT NULL,
  amount NUMERIC(15,2) NOT NULL CHECK (amount > 0),
  transaction_date DATE NOT NULL,
  note VARCHAR(1000),
  FOREIGN KEY (wallet_id, user_id) REFERENCES wallets(id, user_id),
  FOREIGN KEY (category_id, user_id) REFERENCES categories(id, user_id)
);
CREATE TABLE IF NOT EXISTS budgets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  category_id BIGINT NOT NULL,
  budget_month VARCHAR(7) NOT NULL,
  amount_limit NUMERIC(15,2) NOT NULL CHECK (amount_limit > 0),
  FOREIGN KEY (category_id, user_id) REFERENCES categories(id, user_id),
  UNIQUE (user_id, category_id, budget_month)
);
CREATE TABLE IF NOT EXISTS goals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name VARCHAR(100) NOT NULL,
  target_amount NUMERIC(15,2) NOT NULL CHECK (target_amount > 0),
  saved_amount NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (saved_amount >= 0 AND saved_amount <= target_amount),
  deadline DATE NOT NULL,
  icon VARCHAR(20) NOT NULL CHECK (icon IN ('target','plane','laptop','home'))
);
CREATE TABLE IF NOT EXISTS bills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name VARCHAR(100) NOT NULL,
  amount NUMERIC(15,2) NOT NULL CHECK (amount > 0),
  due_date DATE NOT NULL,
  status VARCHAR(10) NOT NULL CHECK (status IN ('unpaid','paid')),
  note VARCHAR(1000)
);
CREATE TABLE IF NOT EXISTS debts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  person VARCHAR(100) NOT NULL,
  direction VARCHAR(10) NOT NULL CHECK (direction IN ('payable','receivable')),
  amount NUMERIC(15,2) NOT NULL CHECK (amount > 0),
  paid_amount NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0 AND paid_amount <= amount),
  due_date DATE NOT NULL,
  note VARCHAR(1000)
);
CREATE TABLE IF NOT EXISTS notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(100) NOT NULL,
  content VARCHAR(2000) NOT NULL,
  label VARCHAR(20) NOT NULL CHECK (label IN ('planning','reminder','idea')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_wallets_owner ON wallets(user_id);
CREATE INDEX IF NOT EXISTS idx_categories_owner ON categories(user_id);
CREATE INDEX IF NOT EXISTS idx_transactions_owner_date ON transactions(user_id, transaction_date);
CREATE INDEX IF NOT EXISTS idx_transactions_wallet ON transactions(wallet_id, user_id);
CREATE INDEX IF NOT EXISTS idx_transactions_category ON transactions(category_id, user_id);
CREATE INDEX IF NOT EXISTS idx_goals_owner ON goals(user_id);
CREATE INDEX IF NOT EXISTS idx_bills_owner_due ON bills(user_id, due_date);
CREATE INDEX IF NOT EXISTS idx_debts_owner_due ON debts(user_id, due_date);
CREATE INDEX IF NOT EXISTS idx_notes_owner ON notes(user_id);
